//! `agents` view (0.3.46, deno study F2): one source for every
//! agent-instructions file. deno keeps CLAUDE.md and a near-copy in
//! `.github/copilot-instructions.md` by hand; they drift. harna owns a
//! managed block — between `<!-- harna:begin -->` and `<!-- harna:end -->`
//! — in each instructions file that carries the markers, rendered from
//! `.harna/` (rules, commands, layers). Prose outside the block stays the
//! humans'; a file without markers is never touched. `harna render`
//! writes, `harna render --check` gates on drift.

use std::path::Path;

use crate::schema::model::manifest::Manifest;
use crate::schema::model::rules::Rules;
use crate::schema::registers::commands::Commands;

pub const BEGIN: &str = "<!-- harna:begin";
pub const END: &str = "<!-- harna:end -->";

/// The instruction files harna may keep a block in.
pub const FILES: &[&str] = &["AGENTS.md", "CLAUDE.md", ".github/copilot-instructions.md"];

/// The block body, markers included.
pub fn block(manifest: &Manifest, rules: &Rules, commands: &Commands) -> String {
    let mut out = String::from(
        "<!-- harna:begin — generated by `harna render` from .harna/; edit the data, not this block -->\n",
    );
    let live: Vec<_> = rules.rules.iter().filter(|r| !r.is_deprecated()).collect();
    if !live.is_empty() {
        out.push_str("### Rules\n\n");
        for r in live {
            let mut tail = Vec::new();
            if !r.scope.is_empty() {
                tail.push(format!("scope: {}", r.scope.join(", ")));
            }
            if let Some(sig) = &r.scope_signature {
                tail.push(format!("applies to code declaring: `{sig}`"));
            }
            if let Some(c) = &r.check {
                tail.push(format!("check: {c}"));
            }
            if let Some(c) = &r.command {
                tail.push(format!("proof: `{c}`"));
            }
            if let Some(e) = &r.env {
                tail.push(format!("env: {e}"));
            }
            let tail = if tail.is_empty() {
                String::new()
            } else {
                format!(" ({})", tail.join("; "))
            };
            out.push_str(&format!(
                "- `{}`: {} — why: {}{tail}\n",
                r.id, r.text, r.rationale
            ));
        }
        out.push('\n');
    }
    if !commands.is_empty() {
        out.push_str("### Commands\n\n");
        for c in &commands.commands {
            out.push_str(&format!(
                "- `{}` — {} [{}]\n",
                c.run,
                c.proves,
                if c.runs.is_empty() { "both" } else { &c.runs }
            ));
        }
        out.push('\n');
    }
    if !manifest.is_empty() {
        out.push_str("### Layers\n\n");
        for l in &manifest.layers {
            let deps = if l.depends_on.is_empty() {
                "nothing".to_string()
            } else {
                l.depends_on.join(", ")
            };
            out.push_str(&format!("- `{}` may import: {deps}\n", l.name));
        }
        out.push('\n');
    }
    out.push_str(END);
    out
}

/// One instructions file's state: (path, stale?). Files without markers
/// are not listed.
pub fn sync(
    root: &Path,
    manifest: &Manifest,
    rules: &Rules,
    commands: &Commands,
    write: bool,
) -> anyhow::Result<Vec<(String, bool)>> {
    let wanted = block(manifest, rules, commands);
    let mut out = Vec::new();
    for f in FILES {
        let path = root.join(f);
        let Ok(text) = std::fs::read_to_string(&path) else {
            continue;
        };
        let (Some(b), Some(e)) = (text.find(BEGIN), text.find(END)) else {
            continue;
        };
        if e < b {
            anyhow::bail!("{f}: `{END}` comes before `{BEGIN}`");
        }
        let current = &text[b..e + END.len()];
        let stale = current.replace("\r\n", "\n") != wanted;
        if stale && write {
            let next = format!("{}{}{}", &text[..b], wanted, &text[e + END.len()..]);
            crate::schema::store::atomic::write(&path, next)?;
        }
        out.push((f.to_string(), stale));
    }
    Ok(out)
}

/// Where AGENTS.md stands for harna (0.3.47, H11).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Opted {
    /// no AGENTS.md at the root
    Missing,
    /// a hand-written AGENTS.md without the managed block
    Hand,
    /// the managed block is there
    Managed,
}

pub fn opted(root: &Path) -> Opted {
    match std::fs::read_to_string(root.join("AGENTS.md")) {
        Err(_) => Opted::Missing,
        Ok(t) if t.contains(BEGIN) && t.contains(END) => Opted::Managed,
        Ok(_) => Opted::Hand,
    }
}

/// `harna init --agents`: opt AGENTS.md in. A hand-written file gains only
/// the (empty) managed block at its end — its prose is never rewritten
/// (zed's and ruff's study clones got ~65 lines of stock contract); a
/// missing one is created from `template` plus the block. `harna render`
/// fills the block. Returns the state found before.
pub fn opt_in(root: &Path, template: &str) -> anyhow::Result<Opted> {
    let path = root.join("AGENTS.md");
    let empty = format!("{BEGIN} -->\n{END}\n");
    let found = opted(root);
    let next = match found {
        Opted::Managed => return Ok(found),
        Opted::Missing => format!("{template}\n{empty}"),
        Opted::Hand => {
            let mut body = std::fs::read_to_string(&path)?;
            if !body.ends_with('\n') {
                body.push('\n');
            }
            format!("{body}\n{empty}")
        }
    };
    crate::schema::store::atomic::write(&path, next)?;
    Ok(found)
}

