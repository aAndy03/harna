//! View `agents-scoped` (0.7.6): instructions where the code is.
//!
//! The root AGENTS.md speaks for the whole repository; an agent working
//! in `crates/ledger/src` needs the part that applies there. A container
//! folder's `AGENTS.md` carrying harna's markers gets a block with only
//! its scope: its layer and what that layer may import, its owners, its
//! declared surface, and the rules whose scope covers it.
//! `harna render --scope <container>` creates the file (opt-in, like
//! `init --agents`); `harna render` keeps every scoped file current, and
//! preflight's views gate reports a stale one.

use std::path::Path;

use super::{BEGIN, END};
use crate::schema::model::manifest::Manifest;
use crate::schema::model::rules::Rules;

/// The block for one container, or None when it has no folder.
pub fn block(manifest: &Manifest, rules: &Rules, container: &str) -> Option<String> {
    let (l, c) = manifest
        .layers
        .iter()
        .flat_map(|l| l.containers.iter().map(move |c| (l, c)))
        .find(|(_, c)| c.name == container)?;
    if crate::schema::model::scope::normalize_scope(&c.path).is_empty() {
        return None; // the repository root is the root AGENTS.md's (0.7.7)
    }
    let mut out = format!(
        "{BEGIN} — generated by `harna render` from .harna/ for container `{}`; edit the data, not this block -->\n",
        c.name
    );
    out.push_str(&format!(
        "\n## `{}` (layer `{}`)\n\n{}\n\n",
        c.name,
        l.name,
        if c.description.is_empty() {
            "(no description declared)"
        } else {
            &c.description
        }
    ));
    out.push_str(&format!(
        "- May import: {}{}\n",
        if l.depends_on.is_empty() {
            "its own layer only".to_string()
        } else {
            format!("its layer and {}", l.depends_on.join(", "))
        },
        if l.isolated {
            " — never a sibling container of this layer"
        } else {
            ""
        }
    ));
    // the answer `harna owners` gives (0.7.7)
    let owners = crate::schema::model::manifest::owners_of(
        manifest,
        &format!(
            "{}/x",
            crate::schema::model::scope::normalize_scope(&c.path)
        ),
    );
    if !owners.is_empty() {
        out.push_str(&format!("- Owners: {}\n", owners.join(", ")));
    }
    if !c.provides.is_empty() {
        out.push_str(&format!(
            "- Surface others may import: {}\n",
            c.provides.join(", ")
        ));
    }
    if let Some(g) = &c.gateway {
        out.push_str(&format!("- Gateway: only this container touches {g}\n"));
    }
    let here: Vec<_> = rules
        .rules
        .iter()
        .filter(|r| !r.is_deprecated() && !r.scope.is_empty())
        .filter(|r| {
            r.scope.iter().any(|s| {
                crate::schema::model::scope::path_within(&c.path, s)
                    || crate::schema::model::scope::path_within(s, &c.path)
            })
        })
        .collect();
    if !here.is_empty() {
        out.push_str("\n### Rules here\n\n");
        for r in here {
            out.push_str(&format!(
                "- `{}`: {} — why: {}\n",
                r.id, r.text, r.rationale
            ));
        }
    }
    out.push_str("\nRepository-wide rules: `harna rules` (and the root agent file, when the repository keeps one).\n");
    out.push_str(END);
    Some(out)
}

/// Every container folder's AGENTS.md / CLAUDE.md with markers: (path,
/// stale?). Claude Code reads CLAUDE.md in subfolders, other agents
/// AGENTS.md (0.7.7: both are kept).
pub fn sync(
    root: &Path,
    manifest: &Manifest,
    rules: &Rules,
    write: bool,
) -> anyhow::Result<Vec<(String, bool)>> {
    let manifest = &crate::schema::store::services::owners_view(root, manifest);
    let mut out = Vec::new();
    for c in manifest.layers.iter().flat_map(|l| &l.containers) {
        let dir = crate::schema::model::scope::normalize_scope(&c.path);
        if dir.is_empty() {
            continue;
        }
        for file in ["AGENTS.md", "CLAUDE.md"] {
            let rel = format!("{dir}/{file}");
            let path = root.join(&rel);
            let Ok(text) = std::fs::read_to_string(&path) else {
                continue;
            };
            // the END closing this block is the first after BEGIN (0.7.7:
            // prose quoting the marker above the block panicked)
            let Some(b) = text.find(BEGIN) else {
                continue;
            };
            let Some(e) = text[b..].find(END).map(|e| b + e) else {
                continue;
            };
            let Some(wanted) = block(manifest, rules, &c.name) else {
                continue;
            };
            let stale = text[b..e + END.len()].replace("\r\n", "\n") != wanted;
            if stale && write {
                let next = format!("{}{}{}", &text[..b], wanted, &text[e + END.len()..]);
                crate::schema::store::atomic::write(&path, next)?;
            }
            out.push((rel, stale)); // written when `write`
        }
    }
    Ok(out)
}

/// Create (or add markers to) a container's AGENTS.md. Returns its path.
pub fn create(
    root: &Path,
    manifest: &Manifest,
    rules: &Rules,
    container: &str,
) -> anyhow::Result<String> {
    let manifest = &crate::schema::store::services::owners_view(root, manifest);
    let Some(wanted) = block(manifest, rules, container) else {
        anyhow::bail!(
            "no container `{container}` with a folder (harna container add / set --path)"
        );
    };
    let c = manifest
        .layers
        .iter()
        .flat_map(|l| &l.containers)
        .find(|c| c.name == container)
        .expect("block found it");
    let dir = crate::schema::model::scope::normalize_scope(&c.path);
    if !root.join(&dir).is_dir() {
        anyhow::bail!(
            "container `{container}`'s folder `{dir}` does not exist yet — create its code first"
        );
    }
    let rel = format!("{dir}/AGENTS.md");
    let path = root.join(&rel);
    let text = std::fs::read_to_string(&path).unwrap_or_default();
    let found = text
        .find(BEGIN)
        .and_then(|b| text[b..].find(END).map(|e| (b, b + e)));
    let next = match found {
        Some((b, e)) => format!("{}{}{}", &text[..b], wanted, &text[e + END.len()..]),
        None if text.is_empty() => format!("# Agent instructions — `{container}`\n\n{wanted}\n"),
        None => format!("{}\n\n{wanted}\n", text.trim_end()),
    };
    crate::schema::store::atomic::write(&path, next)?;
    Ok(rel)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::schema::model::manifest::{Container, Layer};
    use crate::schema::model::rules::Rule;

    /// 0.7.6: a scoped file carries its container's layer reach, owners,
    /// surface and the rules covering it — not the others; hand prose
    /// around the block survives; a stale block is found.
    #[test]
    fn a_container_folder_gets_its_own_instructions() {
        let root = std::env::temp_dir().join(format!("harna-scoped-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&root);
        std::fs::create_dir_all(&root).unwrap();
        let mut m = Manifest {
            layers: vec![Layer {
                name: "core".into(),
                depends_on: vec!["shared".into()],
                containers: vec![Container {
                    name: "ledger".into(),
                    path: "crates/ledger/src".into(),
                    owners: vec!["@ledger".into()],
                    provides: vec!["post".into()],
                    ..Default::default()
                }],
                ..Default::default()
            }],
            ..Default::default()
        };
        let mut rules = Rules::default();
        let rule = |id: &str, scope: &str| Rule {
            id: id.into(),
            text: format!("{id} text"),
            rationale: "r".into(),
            scope: vec![scope.into()],
            ..Default::default()
        };
        rules.rules.push(rule("exact-money", "crates/ledger"));
        rules.rules.push(rule("ui-only", "crates/ui"));
        assert!(
            create(&root, &m, &rules, "ledger").is_err(),
            "no folder yet: refused"
        );
        std::fs::create_dir_all(root.join("crates/ledger/src")).unwrap();
        let rel = create(&root, &m, &rules, "ledger").unwrap();
        let text = std::fs::read_to_string(root.join(&rel)).unwrap();
        assert!(text.contains("May import: its layer and shared"));
        assert!(
            text.contains("Owners: @ledger") && text.contains("Surface others may import: post")
        );
        assert!(text.contains("`exact-money`") && !text.contains("ui-only"));
        // prose quoting the end marker above the block (0.7.7: panicked)
        std::fs::write(
            root.join(&rel),
            format!("Hand note: blocks end with {END}.\n\n{text}"),
        )
        .unwrap();
        assert_eq!(
            sync(&root, &m, &rules, false).unwrap(),
            vec![(rel.clone(), false)]
        );
        m.layers[0].containers[0].owners = vec!["@new".into()];
        assert_eq!(
            sync(&root, &m, &rules, false).unwrap(),
            vec![(rel.clone(), true)]
        );
        sync(&root, &m, &rules, true).unwrap();
        let after = std::fs::read_to_string(root.join(&rel)).unwrap();
        assert!(after.starts_with("Hand note:") && after.contains("Owners: @new"));
        let _ = std::fs::remove_dir_all(&root);
    }
}
