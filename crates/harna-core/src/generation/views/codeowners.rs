//! View `codeowners` (0.7.1): review routing the forge enforces.
//!
//! When the manifest names owners, `harna render` writes
//! `.github/CODEOWNERS` from them: one line per container path, its owners
//! (or its layer's). Lines are ordered so a nested container comes after
//! the one holding it (CODEOWNERS: the last match wins). The file is
//! harna's only when it carries harna's header; a hand-written CODEOWNERS
//! is never touched, and stays the project's to merge by hand.

use std::path::Path;

use crate::schema::model::manifest::Manifest;

pub const FILE: &str = ".github/CODEOWNERS";
const HEADER: &str = "# Generated by `harna render` from .harna/manifest.toml owners — edit the data, not this file.";

/// The CODEOWNERS text, or None when no owner is declared.
pub fn render(manifest: &Manifest) -> Option<String> {
    render_at(manifest, "")
}

/// The CODEOWNERS text with every path under `prefix` (the harna root's
/// folder inside the git repository, `codex-rs/`): GitHub reads paths from
/// the repository root.
pub fn render_at(manifest: &Manifest, prefix: &str) -> Option<String> {
    let mut lines: Vec<(String, Vec<String>)> = Vec::new();
    for c in manifest.layers.iter().flat_map(|l| &l.containers) {
        let path = crate::schema::model::scope::normalize_scope(&c.path);
        if path.is_empty() {
            continue;
        }
        // the same answer `harna owners` gives (0.7.7): the innermost
        // container naming owners, then the enclosing ones, then the layer
        let owners = crate::schema::model::manifest::owners_of(manifest, &format!("{path}/x"));
        if owners.is_empty() {
            continue;
        }
        // a `<root>/src` container answers for its crate root (0.7.7)
        let line = crate::schema::model::manifest::owner_root(&path).unwrap_or(path);
        if !lines.iter().any(|(p, _)| *p == line) {
            lines.push((line, owners));
        }
    }
    if lines.is_empty() {
        return None;
    }
    // shallower first, so a nested container's line wins
    lines.sort_by(|a, b| {
        a.0.matches('/')
            .count()
            .cmp(&b.0.matches('/').count())
            .then(a.0.cmp(&b.0))
    });
    let mut out = format!("{HEADER}\n\n");
    for (path, owners) in lines {
        // CODEOWNERS escapes a space in a path with a backslash
        out.push_str(&format!(
            "/{prefix}{}/ {}\n",
            path.replace(' ', "\\ "),
            owners.join(" ")
        ));
    }
    Some(out)
}

/// Where CODEOWNERS stands after a sync.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Owners {
    /// Matches the declared owners.
    Current,
    /// Differs (check mode: nothing written).
    Stale,
    /// Written or removed just now.
    Written,
    /// A hand-written file holds the path; the declared owners are not in
    /// it (0.7.7: this was silent).
    HandWritten,
}

impl Owners {
    /// The line render prints, if any.
    pub fn note(self) -> Option<String> {
        match self {
            Owners::Current => None,
            Owners::Stale => Some(format!("{FILE} is stale — run `harna render` and commit")),
            Owners::Written => Some(format!("rendered {FILE}")),
            Owners::HandWritten => Some(format!(
                "{FILE} is hand-written: the declared owners are not in it (merge by hand, or delete it and render)"
            )),
        }
    }
}

/// Brings CODEOWNERS in line with the declared owners (`write`), or
/// reports how it stands. None: no owners declared and no harna file.
pub fn sync(root: &Path, manifest: &Manifest, write: bool) -> anyhow::Result<Option<Owners>> {
    // services' owners stand in for containers naming none (0.8.4)
    let manifest = &crate::schema::store::services::owners_view(root, manifest);
    // GitHub reads CODEOWNERS at the repository root, paths from there: a
    // harna root in a git subfolder writes it there, prefixed (0.9.2, codex
    // field test: `codex-rs/.github/CODEOWNERS` is never read)
    let (repo_root, prefix) = crate::search::digest::git_place(root);
    let path = repo_root.join(FILE);
    let current = std::fs::read_to_string(&path).ok();
    let Some(text) = render_at(manifest, &prefix) else {
        // owners all cleared: harna's file goes too (0.7.7: it lingered)
        if current.as_deref().is_some_and(|c| c.starts_with(HEADER)) {
            if write {
                std::fs::remove_file(&path)?;
                return Ok(Some(Owners::Written));
            }
            return Ok(Some(Owners::Stale));
        }
        return Ok(None);
    };
    if current.as_deref().is_some_and(|c| !c.starts_with(HEADER)) {
        return Ok(Some(Owners::HandWritten)); // the project's, untouched
    }
    let stale = current.as_deref().map(|c| c.replace("\r\n", "\n")) != Some(text.clone());
    if !stale {
        return Ok(Some(Owners::Current));
    }
    if write {
        std::fs::create_dir_all(path.parent().expect("has a parent"))?;
        crate::schema::store::atomic::write(&path, &text)?;
        return Ok(Some(Owners::Written));
    }
    Ok(Some(Owners::Stale))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::schema::model::manifest::{Container, Layer};

    /// 0.7.1: container owners (else the layer's) become CODEOWNERS lines,
    /// nested ones last; a hand-written file is never touched.
    #[test]
    fn owners_render_into_codeowners() {
        let c = |name: &str, path: &str, owners: &[&str]| Container {
            name: name.into(),
            path: path.into(),
            owners: owners.iter().map(|s| s.to_string()).collect(),
            ..Default::default()
        };
        let m = Manifest {
            layers: vec![Layer {
                name: "core".into(),
                owners: vec!["@core".into()],
                containers: vec![
                    c("fx", "crates/ledger/src/fx", &["@fx", "ana@example.com"]),
                    c("ledger", "crates/ledger/src", &[]),
                ],
                ..Default::default()
            }],
            ..Default::default()
        };
        let text = render(&m).unwrap();
        let body: Vec<&str> = text.lines().skip(2).collect();
        assert_eq!(
            body,
            vec![
                "/crates/ledger/ @core",
                "/crates/ledger/src/fx/ @fx ana@example.com"
            ]
        );
        // the crate root answers to its src container
        assert_eq!(
            crate::schema::model::manifest::owners_of(&m, "crates/ledger/Cargo.toml"),
            vec!["@core"]
        );
        let root = std::env::temp_dir().join(format!("harna-codeowners-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&root);
        std::fs::create_dir_all(&root).unwrap();
        assert_eq!(sync(&root, &m, false).unwrap(), Some(Owners::Stale));
        assert_eq!(sync(&root, &m, true).unwrap(), Some(Owners::Written));
        assert_eq!(sync(&root, &m, true).unwrap(), Some(Owners::Current));
        std::fs::write(root.join(FILE), "* @mine\n").unwrap();
        assert_eq!(
            sync(&root, &m, true).unwrap(),
            Some(Owners::HandWritten),
            "hand-written stays, and says so"
        );
        assert_eq!(
            std::fs::read_to_string(root.join(FILE)).unwrap(),
            "* @mine\n"
        );
        assert!(render(&Manifest::default()).is_none());
        let _ = std::fs::remove_dir_all(&root);
    }
}
