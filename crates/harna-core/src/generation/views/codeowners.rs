//! View `codeowners` (0.7.1): review routing the forge enforces.
//!
//! When the manifest names owners, `harna render` writes
//! `.github/CODEOWNERS` from them: one line per container path, its owners
//! (or its layer's). Lines are ordered so a nested container comes after
//! the one holding it (CODEOWNERS: the last match wins). The file is
//! harna's only when it carries harna's header; a hand-written CODEOWNERS
//! is never touched, and stays the project's to merge by hand.

use std::path::Path;

use crate::schema::model::manifest::Manifest;

pub const FILE: &str = ".github/CODEOWNERS";
const HEADER: &str = "# Generated by `harna render` from .harna/manifest.toml owners — edit the data, not this file.";

/// The CODEOWNERS text, or None when no owner is declared.
pub fn render(manifest: &Manifest) -> Option<String> {
    let mut lines: Vec<(String, Vec<String>)> = Vec::new();
    for l in &manifest.layers {
        for c in &l.containers {
            if c.path.is_empty() {
                continue;
            }
            let owners = if c.owners.is_empty() {
                &l.owners
            } else {
                &c.owners
            };
            if owners.is_empty() {
                continue;
            }
            let path = crate::schema::model::scope::normalize_scope(&c.path);
            lines.push((path, owners.clone()));
        }
    }
    if lines.is_empty() {
        return None;
    }
    // shallower first, so a nested container's line wins
    lines.sort_by(|a, b| {
        a.0.matches('/')
            .count()
            .cmp(&b.0.matches('/').count())
            .then(a.0.cmp(&b.0))
    });
    let mut out = format!("{HEADER}\n\n");
    for (path, owners) in lines {
        out.push_str(&format!("/{path}/ {}\n", owners.join(" ")));
    }
    Some(out)
}

/// (file, stale) when harna manages CODEOWNERS here; `write` brings it up
/// to date (creating it when absent). None: no owners declared, or a
/// hand-written file harna leaves alone.
pub fn sync(
    root: &Path,
    manifest: &Manifest,
    write: bool,
) -> anyhow::Result<Option<(String, bool)>> {
    let Some(text) = render(manifest) else {
        return Ok(None);
    };
    let path = root.join(FILE);
    let current = std::fs::read_to_string(&path).ok();
    if let Some(cur) = &current {
        if !cur.starts_with(HEADER) {
            return Ok(None); // hand-written: the project's
        }
    }
    let stale = current.as_deref().map(|c| c.replace("\r\n", "\n")) != Some(text.clone());
    if write && stale {
        std::fs::create_dir_all(path.parent().expect("has a parent"))?;
        crate::schema::store::atomic::write(&path, &text)?;
        return Ok(Some((FILE.to_string(), false)));
    }
    Ok(Some((FILE.to_string(), stale && current.is_some())))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::schema::model::manifest::{Container, Layer};

    /// 0.7.1: container owners (else the layer's) become CODEOWNERS lines,
    /// nested ones last; a hand-written file is never touched.
    #[test]
    fn owners_render_into_codeowners() {
        let c = |name: &str, path: &str, owners: &[&str]| Container {
            name: name.into(),
            path: path.into(),
            owners: owners.iter().map(|s| s.to_string()).collect(),
            ..Default::default()
        };
        let m = Manifest {
            layers: vec![Layer {
                name: "core".into(),
                owners: vec!["@core".into()],
                containers: vec![
                    c("fx", "crates/ledger/src/fx", &["@fx", "ana@example.com"]),
                    c("ledger", "crates/ledger/src", &[]),
                ],
                ..Default::default()
            }],
            ..Default::default()
        };
        let text = render(&m).unwrap();
        let body: Vec<&str> = text.lines().skip(2).collect();
        assert_eq!(
            body,
            vec![
                "/crates/ledger/src/ @core",
                "/crates/ledger/src/fx/ @fx ana@example.com"
            ]
        );
        let root = std::env::temp_dir().join(format!("harna-codeowners-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&root);
        std::fs::create_dir_all(&root).unwrap();
        assert_eq!(sync(&root, &m, true).unwrap(), Some((FILE.into(), false)));
        assert_eq!(sync(&root, &m, false).unwrap(), Some((FILE.into(), false)));
        std::fs::write(root.join(FILE), "* @mine\n").unwrap();
        assert_eq!(sync(&root, &m, true).unwrap(), None, "hand-written stays");
        assert_eq!(
            std::fs::read_to_string(root.join(FILE)).unwrap(),
            "* @mine\n"
        );
        assert!(render(&Manifest::default()).is_none());
        let _ = std::fs::remove_dir_all(&root);
    }
}
