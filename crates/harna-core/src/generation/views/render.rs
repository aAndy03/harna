//! Component `render`: generated views.
//!
//! Prose drawn from the manifest instead of written by hand: the manifest
//! stays the single source of truth, and views are regenerated onto it —
//! always-current, committed, diffable. Never hand-edit what `harna render`
//! owns; edit the manifest and re-render.
//!
//! v1: ARCHITECTURE.md — full layer/container/component tour in manifest
//! order, including registered tests.
//! 0.3.5: SURFACE.md — the public API per crate/container: declared in the
//! manifest (`provides`), observed from the digest inventory. Sibling of
//! ARCHITECTURE.md: generated, committed, diffable, staleness-gated.

use std::collections::BTreeMap;
use std::path::Path;

use anyhow::Context as _;

use crate::schema::model::manifest::Manifest;
use crate::search::digest::Digest;

const ARCHITECTURE: &str = "ARCHITECTURE.md";
const SURFACE: &str = "SURFACE.md";

/// The ARCHITECTURE.md view, fully derived from the manifest and therefore
/// byte-deterministic for a given manifest + tool version.
pub fn architecture(manifest: &Manifest) -> String {
    let mut out = String::new();

    out.push_str(&format!(
        "# Architecture\n\
\n\
Generated by harna render (v{}) from `.harna/manifest.toml` — the manifest is \
the source of truth. Regenerate with `harna render` after structural \
changes; never hand-edit this file.\n",
        env!("CARGO_PKG_VERSION"),
    ));
    out.push_str(&format!(
        "{} layers · {} containers · {} components\n",
        manifest.layers.len(),
        manifest.container_count(),
        manifest.component_count(),
    ));

    for layer in &manifest.layers {
        out.push_str(&format!("\n## {} — {}\n", layer.name, layer.description));
        if !layer.depends_on.is_empty() {
            out.push_str(&format!("depends on: {}\n", layer.depends_on.join(", ")));
        }
        for container in &layer.containers {
            out.push_str(&format!("\n### {} ({})\n", container.name, container.path));
            if !container.description.is_empty() {
                out.push_str(&format!("{}\n", container.description));
            }
            if !container.sequence.is_empty() {
                out.push_str(&format!("order: {}\n", container.sequence.join(" → ")));
            }
            for comp in &container.components {
                out.push_str(&format!(
                    "- `{}` ({}) — `{}`\n",
                    comp.name,
                    comp.kind_str(),
                    comp.path,
                ));
                if !comp.summary.is_empty() {
                    out.push_str(&format!("      {}\n", comp.summary));
                }
                if !comp.tests.is_empty() {
                    let inline =
                        comp.tests.len() == 1 && comp.tests[0].replace('\\', "/") == comp.path;
                    if inline {
                        out.push_str("      tests: inline\n");
                    } else {
                        out.push_str(&format!(
                            "      tests: {} file(s) — {}\n",
                            comp.tests.len(),
                            comp.tests.join(", ")
                        ));
                    }
                }
                for child in &comp.children {
                    out.push_str(&format!(
                        "  - `{}` ({}) — `{}`\n",
                        child.name,
                        child.kind_str(),
                        child.path,
                    ));
                    if !child.summary.is_empty() {
                        out.push_str(&format!("        {}\n", child.summary));
                    }
                }
            }
        }
    }

    out.push_str("\n---\nCommitted and diffable: structural changes review as view diffs.\n");
    out
}

/// Write the ARCHITECTURE.md view at the repository root.
pub fn write(root: &Path, manifest: &Manifest) -> anyhow::Result<std::path::PathBuf> {
    let path = root.join(ARCHITECTURE);
    std::fs::write(&path, architecture(manifest))
        .with_context(|| format!("writing {}", path.display()))?;
    Ok(path)
}

/// Staleness check: is the committed view exactly what the current manifest
/// renders to? Missing or divergent files are stale.
pub fn is_stale(root: &Path, manifest: &Manifest) -> anyhow::Result<bool> {
    let path = root.join(ARCHITECTURE);
    match std::fs::read_to_string(&path) {
        Ok(current) => Ok(current != architecture(manifest)),
        Err(_) => Ok(true),
    }
}

/// Container hosts, longest path first so nested containers win.
fn container_hosts(
    manifest: &Manifest,
) -> Vec<(
    String, /*layer*/
    String, /*container*/
    String, /*path*/
)> {
    let mut hosts = manifest
        .layers
        .iter()
        .flat_map(|l| {
            l.containers
                .iter()
                .map(|c| (l.name.to_string(), c.name.to_string(), c.path.clone()))
        })
        .collect::<Vec<_>>();
    hosts.sort_by(|a, b| b.2.len().cmp(&a.2.len()).then(a.2.cmp(&b.2)));
    hosts
}

fn host_of<'h>(
    hosts: &'h [(String, String, String)],
    module_path: &str,
) -> Option<&'h (String, String, String)> {
    hosts.iter().find(|(_, _, path)| {
        !path.is_empty()
            && (module_path.starts_with(&format!("{path}/"))
                || module_path
                    .rsplit_once('/')
                    .map(|(dir, _file)| dir == *path)
                    .unwrap_or(false))
    })
}

/// The SURFACE.md view (0.3.5): the public API per crate/container —
/// grouping from the manifest, content from the digest's public surface,
/// plus each container's declared `provides` when set. Byte-deterministic.
pub fn surface(manifest: &Manifest, digest: &Digest) -> String {
    let hosts = container_hosts(manifest);

    // Declared `provides` per container name (itself + components), deduped.
    let mut declared: BTreeMap<String, Vec<String>> = BTreeMap::new();
    for l in &manifest.layers {
        for c in &l.containers {
            let mut p = c.provides.clone();
            fn collect(comps: &[crate::schema::model::manifest::Component], out: &mut Vec<String>) {
                for comp in comps {
                    out.extend(comp.provides.iter().cloned());
                    collect(&comp.children, out);
                }
            }
            collect(&c.components, &mut p);
            p.sort();
            p.dedup();
            if !p.is_empty() {
                declared.insert(c.name.clone(), p);
            }
        }
    }

    // Group modules by crate dir, then by container section, in one pass.
    // crate dir → container section → (declared `provides`, observed surface)
    type Sections = BTreeMap<String, (Option<Vec<String>>, Vec<String>)>;
    let mut grouped: BTreeMap<String, Sections> = BTreeMap::new();
    for m in &digest.modules {
        let crate_dir = crate::search::digest::crate_of(&m.path)
            .0
            .unwrap_or_else(|| ".".into());
        let (section, container) = match host_of(&hosts, &m.path) {
            Some((layer, container, path)) => (
                format!("{container} ({path}) [layer {layer}]"),
                container.to_string(),
            ),
            None => (
                "(ungoverned) (outside declared containers)".to_string(),
                String::new(),
            ),
        };
        let entry = grouped
            .entry(crate_dir)
            .or_default()
            .entry(section)
            .or_insert((None, Vec::new()));
        if entry.0.is_none() {
            entry.0 = declared.get(&container).cloned();
        }
        entry.1.push(format!("- {}", m.path));
        for sig in &m.signatures {
            entry.1.push(format!("    {}", sig.trim_end()));
        }
    }

    let mut out = String::new();
    out.push_str(&format!(
        "# Surface\n\nGenerated by harna render (v{}) from `.harna/manifest.toml` + `.harna/digest.json` — \
         the public API per crate/container as the committed map sees it. Regenerate with \
         `harna render --surface`; never hand-edit this file.\n",
        env!("CARGO_PKG_VERSION"),
    ));
    for (crate_dir, sections) in &grouped {
        out.push_str(&format!("\n## crate {}\n", crate_dir));
        for (section, (declared, lines)) in sections {
            out.push_str(&format!("\n### {}\n", section));
            if let Some(p) = declared {
                out.push_str(&format!("declared surface (provides): {}\n", p.join(", ")));
            }
            for line in lines {
                out.push_str(line);
                out.push('\n');
            }
        }
    }
    out.push_str("\n---\nCommitted and diffable: surface changes review as view diffs.\n");
    out
}

/// Write SURFACE.md at the repository root.
pub fn write_surface(
    root: &Path,
    manifest: &Manifest,
    digest: &Digest,
) -> anyhow::Result<std::path::PathBuf> {
    let path = root.join(SURFACE);
    std::fs::write(&path, surface(manifest, digest))
        .with_context(|| format!("writing {}", path.display()))?;
    Ok(path)
}

/// Staleness check for the surface view (same recipe as the architecture view).
pub fn surface_is_stale(root: &Path, manifest: &Manifest, digest: &Digest) -> anyhow::Result<bool> {
    let path = root.join(SURFACE);
    match std::fs::read_to_string(&path) {
        Ok(current) => Ok(current != surface(manifest, digest)),
        Err(_) => Ok(true),
    }
}

impl crate::schema::model::manifest::Component {
    fn kind_str(&self) -> &'static str {
        match self.kind {
            crate::schema::model::manifest::ComponentKind::Primitive => "primitive",
            crate::schema::model::manifest::ComponentKind::Compound => "compound",
        }
    }
}

#[cfg(test)]
mod surface_tests {
    use super::*;
    use crate::schema::model::manifest::{Container, Layer};
    use crate::search::digest::{Digest, Module};

    fn surface_fixture() -> (Manifest, Digest) {
        let manifest = Manifest {
            schema_version: 1,
            layers: vec![Layer {
                name: "integrity".into(),
                description: String::new(),
                sequence: vec![],
                depends_on: vec![],
                role: None,
                containers: vec![Container {
                    name: "conformance".into(),
                    path: "crates/t/src/enforcement".into(),
                    description: String::new(),
                    sequence: vec![],
                    provides: vec!["Keeper".into()],
                    role: None,
                    gateway: None,
                    connects: vec![],
                    components: vec![],
                }],
            }],
        };
        let digest = Digest {
            generated_at: "now".into(),
            extractor_version: crate::search::digest::EXTRACTOR_VERSION,
            modules: vec![
                Module {
                    path: "crates/t/src/enforcement/surface.rs".into(),
                    lang: "rust".into(),
                    signatures: vec!["pub fn check() -> Keeper".into()],
                    deps: vec![],
                    body_hash: "x".into(),
                    inventory: vec![],
                    mods: vec![],
                },
                Module {
                    path: "crates/t/src/free.rs".into(),
                    lang: "rust".into(),
                    signatures: vec!["pub struct Loose".into()],
                    deps: vec![],
                    body_hash: "x".into(),
                    inventory: vec![],
                    mods: vec![],
                },
            ],
        };
        (manifest, digest)
    }

    #[test]
    fn surface_view_groups_by_container_and_names_provides() {
        let (manifest, digest) = surface_fixture();
        let view = surface(&manifest, &digest);
        assert!(view.contains("### conformance (crates/t/src/enforcement) [layer integrity]"));
        assert!(view.contains("declared surface (provides): Keeper"));
        assert!(view.contains("pub fn check() -> Keeper"));
        // The ungoverned module gets an honest bucket, not a drop.
        assert!(view.contains("(ungoverned)"));
        assert!(view.contains("pub struct Loose"));
        // Deterministic for the same inputs.
        assert_eq!(surface(&manifest, &digest), view);
    }

    #[test]
    fn surface_staleness_writes_and_detects() -> anyhow::Result<()> {
        let root = std::env::temp_dir().join(format!("harna-surface-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&root);
        std::fs::create_dir_all(&root).unwrap();
        let (manifest, digest) = surface_fixture();

        assert!(surface_is_stale(&root, &manifest, &digest)?, "no view yet");
        let path = write_surface(&root, &manifest, &digest)?;
        assert!(path.ends_with("SURFACE.md"));
        assert!(!surface_is_stale(&root, &manifest, &digest)?);

        // A changed digest moves the view (content, not mtime).
        let mut d2 = digest.clone();
        d2.modules[0].signatures.push("pub fn check2()".into());
        assert!(surface_is_stale(&root, &manifest, &d2)?);
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::schema::model::manifest::{Component, ComponentKind, Container, Layer};

    fn component(name: &str, path: &str, summary: &str, tests: &[&str]) -> Component {
        Component {
            name: name.into(),
            kind: ComponentKind::Primitive,
            path: path.into(),
            summary: summary.into(),
            tests: tests.iter().map(|s| s.to_string()).collect(),
            provides: vec![],
            children: vec![],
        }
    }

    fn manifest() -> Manifest {
        Manifest {
            schema_version: 1,
            layers: vec![
                Layer {
                    name: "memory".into(),
                    description: "everything known lives in the repo".into(),
                    sequence: vec![],
                    depends_on: vec!["search".into()],
                    role: None,
                    containers: vec![Container {
                        name: "schema".into(),
                        path: "src/schema".into(),
                        description: "data model".into(),
                        sequence: vec![],
                        provides: vec![],
                        role: None,
                        gateway: None,
                        connects: vec![],
                        components: vec![
                            component(
                                "store",
                                "src/schema/store.rs",
                                "persistence",
                                &["src/schema/store.rs"],
                            ),
                            component("migrate", "src/schema/migrate.rs", "upgrades", &[]),
                        ],
                    }],
                },
                Layer {
                    name: "search".into(),
                    description: "queryable views".into(),
                    sequence: vec![],
                    depends_on: vec![],
                    role: None,
                    containers: vec![Container {
                        name: "code-map".into(),
                        path: "src/search".into(),
                        description: String::new(),
                        sequence: vec!["digest".into()],
                        provides: vec![],
                        role: None,
                        gateway: None,
                        connects: vec![],
                        components: vec![component(
                            "digest",
                            "src/search/digest.rs",
                            "the map",
                            &[],
                        )],
                    }],
                },
            ],
        }
    }

    #[test]
    fn view_is_deterministic_and_complete() {
        let m = manifest();
        let a = architecture(&m);
        assert_eq!(a, architecture(&m), "same manifest -> same bytes");

        assert!(a.contains("# Architecture"));
        assert!(a.contains("harna render"));
        assert!(a.contains("2 layers · 2 containers · 3 components"));
        assert!(a.contains("## memory — everything known lives in the repo"));
        assert!(a.contains("depends on: search"));
        assert!(a.contains("### schema (src/schema)"));
        assert!(a.contains("- `store` (primitive) — `src/schema/store.rs`"));
        assert!(a.contains("      persistence"));
        // A test path equal to the component itself reads as inline.
        assert!(a.contains("      tests: inline"));
        assert!(a.contains("order: digest"));
    }

    #[test]
    fn staleness_checks_the_committed_view() -> anyhow::Result<()> {
        let dir = std::env::temp_dir().join(format!("harna-render-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir)?;
        let m = manifest();

        // Nothing written yet: stale.
        assert!(is_stale(&dir, &m)?);

        let path = write(&dir, &m)?;
        assert_eq!(path.file_name().unwrap(), "ARCHITECTURE.md");
        assert!(!is_stale(&dir, &m)?, "fresh render is current");

        // Any manifest change (even a summary) makes the committed view stale.
        let mut changed = manifest();
        changed.layers[0].containers[0].components[0].summary = "edited".into();
        assert!(is_stale(&dir, &changed)?);
        let _ = std::fs::remove_dir_all(&dir);
        Ok(())
    }

    #[test]
    fn empty_manifest_renders_honestly() {
        let out = architecture(&Manifest::default());
        assert!(out.contains("0 layers · 0 containers · 0 components"));
    }
}
