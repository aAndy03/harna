//! Component `render`: generated views.
//!
//! Prose drawn from the manifest instead of written by hand: the manifest
//! stays the single source of truth, and views are regenerated onto it —
//! always-current, committed, diffable. Never hand-edit what `harna render`
//! owns; edit the manifest and re-render.
//!
//! v1: ARCHITECTURE.md — full layer/container/component tour in manifest
//! order, including registered tests.

use std::path::Path;

use anyhow::Context as _;

use crate::schema::manifest::Manifest;

const ARCHITECTURE: &str = "ARCHITECTURE.md";

/// The ARCHITECTURE.md view, fully derived from the manifest and therefore
/// byte-deterministic for a given manifest + tool version.
pub fn architecture(manifest: &Manifest) -> String {
    let mut out = String::new();

    out.push_str(&format!(
        "# Architecture\n\
\n\
Generated by harna render (v{}) from `.harna/manifest.toml` — the manifest is \
the source of truth. Regenerate with `harna render` after structural \
changes; never hand-edit this file.\n",
        env!("CARGO_PKG_VERSION"),
    ));
    out.push_str(&format!(
        "{} layers · {} containers · {} components\n",
        manifest.layers.len(),
        manifest.container_count(),
        manifest.component_count(),
    ));

    for layer in &manifest.layers {
        out.push_str(&format!("\n## {} — {}\n", layer.name, layer.description));
        if !layer.depends_on.is_empty() {
            out.push_str(&format!("depends on: {}\n", layer.depends_on.join(", ")));
        }
        for container in &layer.containers {
            out.push_str(&format!("\n### {} ({})\n", container.name, container.path));
            if !container.description.is_empty() {
                out.push_str(&format!("{}\n", container.description));
            }
            if !container.sequence.is_empty() {
                out.push_str(&format!("order: {}\n", container.sequence.join(" → ")));
            }
            for comp in &container.components {
                out.push_str(&format!(
                    "- `{}` ({}) — `{}`\n",
                    comp.name,
                    comp.kind_str(),
                    comp.path,
                ));
                if !comp.summary.is_empty() {
                    out.push_str(&format!("      {}\n", comp.summary));
                }
                if !comp.tests.is_empty() {
                    let inline = comp.tests.len() == 1
                        && comp.tests[0].replace('\\', "/") == comp.path;
                    if inline {
                        out.push_str("      tests: inline\n");
                    } else {
                        out.push_str(&format!(
                            "      tests: {} file(s) — {}\n",
                            comp.tests.len(),
                            comp.tests.join(", ")
                        ));
                    }
                }
                for child in &comp.children {
                    out.push_str(&format!(
                        "  - `{}` ({}) — `{}`\n",
                        child.name,
                        child.kind_str(),
                        child.path,
                    ));
                    if !child.summary.is_empty() {
                        out.push_str(&format!("        {}\n", child.summary));
                    }
                }
            }
        }
    }

    out.push_str("\n---\nCommitted and diffable: structural changes review as view diffs.\n");
    out
}

/// Write the ARCHITECTURE.md view at the repository root.
pub fn write(root: &Path, manifest: &Manifest) -> anyhow::Result<std::path::PathBuf> {
    let path = root.join(ARCHITECTURE);
    std::fs::write(&path, architecture(manifest))
        .with_context(|| format!("writing {}", path.display()))?;
    Ok(path)
}

/// Staleness check: is the committed view exactly what the current manifest
/// renders to? Missing or divergent files are stale.
pub fn is_stale(root: &Path, manifest: &Manifest) -> anyhow::Result<bool> {
    let path = root.join(ARCHITECTURE);
    match std::fs::read_to_string(&path) {
        Ok(current) => Ok(current != architecture(manifest)),
        Err(_) => Ok(true),
    }
}

impl crate::schema::manifest::Component {
    fn kind_str(&self) -> &'static str {
        match self.kind {
            crate::schema::manifest::ComponentKind::Primitive => "primitive",
            crate::schema::manifest::ComponentKind::Compound => "compound",
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::schema::manifest::{Component, ComponentKind, Container, Layer};

    fn component(name: &str, path: &str, summary: &str, tests: &[&str]) -> Component {
        Component {
            name: name.into(),
            kind: ComponentKind::Primitive,
            path: path.into(),
            summary: summary.into(),
            tests: tests.iter().map(|s| s.to_string()).collect(),
            children: vec![],
        }
    }

    fn manifest() -> Manifest {
        Manifest {
            schema_version: 1,
            layers: vec![
                Layer {
                    name: "memory".into(),
                    description: "everything known lives in the repo".into(),
                    sequence: vec![],
                    depends_on: vec!["search".into()],
                    containers: vec![Container {
                        name: "schema".into(),
                        path: "src/schema".into(),
                        description: "data model".into(),
                        sequence: vec![],
                        components: vec![
                            component("store", "src/schema/store.rs", "persistence", &["src/schema/store.rs"]),
                            component("migrate", "src/schema/migrate.rs", "upgrades", &[],
                            ),
                        ],
                    }],
                },
                Layer {
                    name: "search".into(),
                    description: "queryable views".into(),
                    sequence: vec![],
                    depends_on: vec![],
                    containers: vec![Container {
                        name: "code-map".into(),
                        path: "src/search".into(),
                        description: String::new(),
                        sequence: vec!["digest".into()],
                        components: vec![component("digest", "src/search/digest.rs", "the map", &[])],
                    }],
                },
            ],
        }
    }

    #[test]
    fn view_is_deterministic_and_complete() {
        let m = manifest();
        let a = architecture(&m);
        assert_eq!(a, architecture(&m), "same manifest -> same bytes");

        assert!(a.contains("# Architecture"));
        assert!(a.contains("harna render"));
        assert!(a.contains("2 layers · 2 containers · 3 components"));
        assert!(a.contains("## memory — everything known lives in the repo"));
        assert!(a.contains("depends on: search"));
        assert!(a.contains("### schema (src/schema)"));
        assert!(a.contains("- `store` (primitive) — `src/schema/store.rs`"));
        assert!(a.contains("      persistence"));
        // A test path equal to the component itself reads as inline.
        assert!(a.contains("      tests: inline"));
        assert!(a.contains("order: digest"));
    }

    #[test]
    fn staleness_checks_the_committed_view() -> anyhow::Result<()> {
        let dir = std::env::temp_dir().join(format!("harna-render-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir)?;
        let m = manifest();

        // Nothing written yet: stale.
        assert!(is_stale(&dir, &m)?);

        let path = write(&dir, &m)?;
        assert_eq!(path.file_name().unwrap(), "ARCHITECTURE.md");
        assert!(!is_stale(&dir, &m)?, "fresh render is current");

        // Any manifest change (even a summary) makes the committed view stale.
        let mut changed = manifest();
        changed.layers[0].containers[0].components[0].summary = "edited".into();
        assert!(is_stale(&dir, &changed)?);
        let _ = std::fs::remove_dir_all(&dir);
        Ok(())
    }

    #[test]
    fn empty_manifest_renders_honestly() {
        let out = architecture(&Manifest::default());
        assert!(out.contains("0 layers · 0 containers · 0 components"));
    }
}
