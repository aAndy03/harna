//! Component `notes` (0.3.22): collaboration drafts, rendered from data.
//!
//! Both notes are stdout exports (the established doctrine — data for the
//! reviewer, summary for stderr, the composer never writes). Neither
//! judges: a checklist names what to look at, a release note names what
//! happened — the author reads, prunes, and speaks.
//!
//! - **Review checklist** — from an open parity event's fan-out (or a
//!   ref-spanning diff), the scoped rules watching the changed paths, and
//!   the registered tests belonging to the changed components. The three
//!   sources every review needs open, on one page.
//! - **Release-note draft** — decisions recorded since a ref + parity
//!   events opened between that ref and now (live ledger and the filed
//!   archive both read). "Since the ref" reads the committed ledgers via
//!   git ls-tree against the current tree — the briefing container owns
//!   the process gateway, so git subprocess calls stay home.

use std::collections::BTreeSet;
use std::path::Path;

use crate::enforcement::parity::{self, ParityEvent};
use crate::schema::model::manifest::Manifest;
use crate::schema::store::Store;
use crate::search::diff;
use crate::search::digest::Digest;

fn git_out(root: &Path, args: &[&str]) -> Option<String> {
    std::process::Command::new("git")
        .args(args)
        .current_dir(root)
        .output()
        .ok()
        .filter(|o| o.status.success())
        .map(|o| String::from_utf8_lossy(&o.stdout).into_owned())
}

fn header(out: &mut String, title: &str) {
    out.push_str(&format!(
        "# {title}\n\nGenerated by harna notes (v{}) — a draft to prune, not prose to ship as-is.\n",
        env!("CARGO_PKG_VERSION")
    ));
}

/// Changed module paths when reviewing a ref span instead of an event.
fn paths_from_diff(root: &Path, from: &str, digest: &Digest) -> anyhow::Result<Vec<String>> {
    let baseline = diff::digest_at_ref(root, from)?;
    let d = diff::diff(&baseline, digest);
    let mut paths: BTreeSet<String> = BTreeSet::new();
    paths.extend(d.modules_added.iter().cloned());
    paths.extend(d.modules_removed.iter().cloned());
    paths.extend(d.signatures_added.iter().map(|(p, _)| p.clone()));
    paths.extend(d.signatures_removed.iter().map(|(p, _)| p.clone()));
    paths.extend(d.deps_added.iter().map(|(p, _)| p.clone()));
    paths.extend(d.contents_changed.iter().cloned());
    Ok(paths.into_iter().collect())
}

/// The review checklist. `id` pins the survey to one parity event; else
/// the last `--from` ref is diffed (`HEAD` by default).
pub fn review(store: &Store, id: Option<&str>, from: Option<&str>) -> anyhow::Result<String> {
    let root = store.repo_root();
    let manifest: Manifest = store.load_manifest()?;
    let digest = store.load_digest()?;
    let rules_doc = store.load_rules()?;

    let (event_label, targets, paths) = if let Some(id) = id {
        let ev = parity::event(store, id)?;
        (format!("parity event `{id}`"), Some(ev.clone()), {
            let mut p = ev
                .targets
                .iter()
                .map(|t| t.path.clone())
                .collect::<Vec<_>>();
            p.sort();
            p
        })
    } else {
        let spec = from.unwrap_or("HEAD");
        (
            format!("diff from `{spec}`"),
            None,
            paths_from_diff(&root, spec, &digest)?,
        )
    };
    if paths.is_empty() {
        anyhow::bail!("nothing changed in this range — nothing to review");
    }

    let mut out = String::new();
    header(&mut out, &format!("Review checklist — {event_label}"));

    out.push_str(&format!("\n## What moved ({} module(s))\n", paths.len()));
    for p in &paths {
        let note = targets
            .as_ref()
            .and_then(|ev| ev.target(p))
            .map(|t| format!(" — {}/{}", t.status, t.reason))
            .unwrap_or_default();
        out.push_str(&format!("- [ ] `{p}`{note}\n"));
    }

    // Rules in scope: every rule whose scope covers a changed path,
    // deduped by id; rationale rides along — that is the point.
    let mut seen = BTreeSet::new();
    let mut in_scope = Vec::new();
    for p in &paths {
        for r in rules_doc.for_scope(p) {
            if seen.insert(r.id.clone()) {
                in_scope.push(r);
            }
        }
    }
    if !in_scope.is_empty() {
        out.push_str(&format!(
            "\n## Rules watching these paths ({})\n",
            in_scope.len()
        ));
        for r in in_scope {
            out.push_str(&format!(
                "- [ ] `{}` — {}\n  why: {}\n",
                r.id, r.text, r.rationale
            ));
        }
    }

    // Registered tests of the changed components (component path == module
    // path for primitives), deduped, runnable invocations named.
    let mut tests: Vec<String> = Vec::new();
    let mut test_seen = BTreeSet::new();
    let mut components: Vec<&crate::schema::model::manifest::Component> = manifest
        .layers
        .iter()
        .flat_map(|l| l.containers.iter().flat_map(|c| c.components.iter()))
        .collect();
    components.sort_by(|a, b| a.path.cmp(&b.path));
    for p in &paths {
        for comp in &components {
            if comp.path != *p {
                continue;
            }
            for t in &comp.tests {
                if test_seen.insert(t.clone()) {
                    tests.push(t.clone());
                }
            }
        }
    }
    if !tests.is_empty() {
        out.push_str(&format!(
            "\n## Registered tests over these components ({})\n",
            tests.len()
        ));
        let coverage =
            crate::enforcement::validate::coherence::test_coverage::runnable(&root, &manifest);
        for t in &tests {
            let runner = coverage
                .iter()
                .find(|c| &c.test == t)
                .map(|c| {
                    if c.runnable() {
                        format!("`{}`", c.command)
                    } else {
                        format!("not runnable — {}", c.note)
                    }
                })
                .unwrap_or_else(|| "not registered in the coverage map".to_string());
            out.push_str(&format!("- [ ] `{t}` — {runner}\n"));
        }
    }
    Ok(out)
}

/// The release-note draft from decisions + parity between a ref and now.
pub fn release(store: &Store, from: &str) -> anyhow::Result<String> {
    diff::check_ref(from)?;
    let root = store.repo_root();

    // Paths present now but not at the ref — the readable, honest "since
    // then" for both ledgers. No git → nothing can be compared; the draft
    // says so rather than pretending.
    let git_at = |path: &str| -> BTreeSet<String> {
        git_out(&root, &["ls-tree", "-r", "--name-only", from, "--", path])
            .unwrap_or_default()
            .lines()
            .map(|s| s.to_string())
            .collect()
    };
    let has_git = git_out(&root, &["rev-parse", "HEAD"]).is_some();

    let mut out = String::new();
    header(&mut out, &format!("Release note draft — since `{from}`"));

    if !has_git {
        out.push_str("\n(no git history available — nothing can be compared against the ref)\n");
        return Ok(out);
    }

    // Decisions: live log first, file archive behind it (0.3.18
    // resolution — a filed decision is history, still readable). Each
    // shelf compares against ITS ledger path at the ref: a live decision
    // under `.harna/decisions`, a filed one under `.harna/archive/
    // decisions` — the archive existed at the ref, so its old contents
    // are by definition not fresh.
    let live_at = git_at(".harna/decisions");
    let archived_at = git_at(".harna/archive/decisions");
    let mut decisions = crate::schema::journal::decisions::list(&store.decisions_dir())?;
    decisions.extend(crate::schema::journal::decisions::list(
        &store.archive_dir().join("decisions"),
    )?);
    decisions.sort_by(|a, b| a.file.cmp(&b.file));
    let fresh: Vec<_> = decisions
        .iter()
        .filter(|d| {
            // A file the ref already knows — on either shelf — is not
            // fresh; only the shelf it sits on NOW decides where to look.
            !live_at.contains(&format!(".harna/decisions/{}", d.file))
                && !archived_at.contains(&format!(".harna/archive/decisions/{}", d.file))
        })
        .collect();
    out.push_str(&format!(
        "\n## Decisions recorded since `{from}` ({})\n",
        fresh.len()
    ));
    for d in &fresh {
        out.push_str(&format!("- `{}` — {}\n", d.file, d.title));
    }

    // Parity: events that appeared after the ref, live + filed, each with
    // its shape at draft time — each shelf against its own ledger path.
    let parity_live_at = git_at(".harna/parity");
    let parity_archived_at = git_at(".harna/archive/parity");
    let mut events: Vec<ParityEvent> = parity::list_events(store)?;
    events.extend(parity::archived_events(store)?);
    events.sort_by(|a, b| a.created.cmp(&b.created).then(a.id.cmp(&b.id)));
    let fresh_events: Vec<_> = events
        .iter()
        .filter(|e| {
            // The same predicate as the decisions: a file the ref already
            // knows — on either shelf — is not fresh.
            !parity_live_at.contains(&format!(".harna/parity/{}.toml", e.id))
                && !parity_archived_at.contains(&format!(".harna/archive/parity/{}.toml", e.id))
        })
        .collect();
    out.push_str(&format!(
        "\n## Parity between `{from}` and now ({})\n",
        fresh_events.len()
    ));
    for ev in &fresh_events {
        out.push_str(&format!(
            "- `{}` — {} target(s), {} open ({})\n",
            ev.id,
            ev.targets.len(),
            ev.open_targets().len(),
            ev.kind
        ));
    }
    if fresh.is_empty() && fresh_events.is_empty() {
        out.push_str(&format!(
            "\nNo decisions or parity events opened between `{from}` and now.\n"
        ));
    }
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::schema::model::manifest::{Component, ComponentKind, Container, Layer, Manifest};
    use crate::schema::model::rules::{Rule, Rules};
    use crate::search::digest::Module;

    fn store() -> Store {
        let tmp = std::env::temp_dir().join(format!(
            "harna-notes-{}-{:?}",
            std::process::id(),
            std::thread::current().id()
        ));
        let _ = std::fs::remove_dir_all(&tmp);
        let s = Store::open(&tmp).unwrap();
        s.init().unwrap();
        s
    }

    fn manifest() -> Manifest {
        Manifest {
            schema_version: crate::SCHEMA_VERSION,
            layers: vec![Layer {
                name: "app".into(),
                description: String::new(),
                sequence: vec![],
                depends_on: vec![],
                role: None,
                containers: vec![Container {
                    name: "lib".into(),
                    path: "crates/x/src".into(),
                    description: String::new(),
                    sequence: vec![],
                    provides: vec![],
                    role: None,
                    gateway: None,
                    connects: vec![],
                    components: vec![Component {
                        name: "store".into(),
                        kind: ComponentKind::Primitive,
                        path: "crates/x/src/store.rs".into(),
                        summary: String::new(),
                        tests: vec!["crates/x/src/store.rs".into()],
                        provides: vec![],
                        children: vec![],
                    }],
                }],
            }],
        }
    }

    fn digest() -> Digest {
        Digest {
            generated_at: "now".into(),
            extractor_version: crate::search::digest::EXTRACTOR_VERSION,
            modules: vec![Module {
                crate_dir: None,
                src_root: None,
                path: "crates/x/src/store.rs".into(),
                lang: "rust".into(),
                signatures: vec!["pub fn load()".into()],
                deps: vec![],
                body_hash: "fixture".into(),
                inventory: vec![],
                mods: vec![],
            }],
        }
    }

    fn event_file(store: &Store, id: &str, target_path: &str) {
        let ev = ParityEvent {
            id: id.into(),
            kind: "digest-diff".into(),
            source: "fixture".into(),
            generation: 1,
            baseline_ref: "HEAD".into(),
            created: "t".into(),
            updated: "t".into(),
            targets: vec![crate::enforcement::parity::ParityTarget {
                path: target_path.into(),
                reason: "changed".into(),
                status: "open".into(),
                note: String::new(),
                by: "t".into(),
                when: String::new(),
                breaking: false,
                history: Vec::new(),
            }],
        };
        let dir = store.manifest_path().parent().unwrap().join("parity");
        std::fs::create_dir_all(&dir).unwrap();
        std::fs::write(
            dir.join(format!("{id}.toml")),
            toml::to_string(&ev).unwrap(),
        )
        .unwrap();
    }

    #[test]
    fn review_checklist_carries_the_three_sources() {
        let s = store();
        let m = manifest();
        s.save_manifest(&m).unwrap();
        s.save_rules(&Rules {
            schema_version: crate::SCHEMA_VERSION,
            rules: vec![Rule {
                id: "no-hardcoded-urls".into(),
                text: "route through endpoints".into(),
                rationale: "endpoints change".into(),
                scope: vec!["crates/x/src".into()],
                tags: vec![],
                origin: "fixture".into(),
                examples: vec![],
                env: None,
                check: None,
                severity: None,
                pattern: None,
                limit: None,
                status: None,
            }],
        })
        .unwrap();
        s.save_digest(&m, &digest()).unwrap();
        event_file(&s, "rev-one", "crates/x/src/store.rs");

        let text = review(&s, Some("rev-one"), None).unwrap();
        assert!(text.contains("crates/x/src/store.rs"), "what moved");
        assert!(text.contains("rev-one"));
        assert!(text.contains("no-hardcoded-urls"), "rules in scope");
        assert!(text.contains("endpoints change"), "the rule's why");
        assert!(
            text.contains("crates/x/src/store.rs"),
            "registered test named"
        );
        let _ = std::fs::remove_dir_all(s.repo_root());
    }

    #[test]
    fn release_draft_lists_decisions_and_events_since_ref() {
        // Anything the fixture needs git for must not touch the outer repo.
        let tmp = std::env::temp_dir().join(format!(
            "harna-notes-git-{}-{:?}",
            std::process::id(),
            std::thread::current().id()
        ));
        let _ = std::fs::remove_dir_all(&tmp);
        let run = |args: &[&str]| {
            std::process::Command::new("git")
                .args(args)
                .current_dir(&tmp)
                .env("GIT_AUTHOR_NAME", "t")
                .env("GIT_AUTHOR_EMAIL", "t@t")
                .env("GIT_COMMITTER_NAME", "t")
                .env("GIT_COMMITTER_EMAIL", "t@t")
                .output()
                .expect("git")
        };
        let s = Store::open(&tmp).unwrap();
        s.init().unwrap();
        run(&["init", "--quiet"]);
        assert!(run(&["add", "."]).status.success());

        // At HEAD: decision A + event A, committed.
        let dir = tmp.join(".harna/decisions");
        std::fs::create_dir_all(&dir).unwrap();
        std::fs::write(dir.join("a.md"), "# Decision A\n").unwrap();
        event_file(&s, "old", "crates/x/src/old.rs");
        run(&["add", "."]);
        assert!(
            run(&["commit", "-q", "-m", "at ref"]).status.success(),
            "the fixture needs a commit"
        );

        // FILED after the ref: the archive shelf did not exist at HEAD
        // for it, but the ref knows the file — not fresh either way.
        std::fs::create_dir_all(tmp.join(".harna/archive/parity")).unwrap();
        std::fs::rename(
            tmp.join(".harna/parity/old.toml"),
            tmp.join(".harna/archive/parity/old.toml"),
        )
        .unwrap();

        // After the ref: decision B + event B, uncommitted.
        std::fs::write(dir.join("b.md"), "# Decision B\n").unwrap();
        event_file(&s, "new", "crates/x/src/new.rs");

        let text = release(&s, "HEAD").unwrap();
        assert!(text.contains("Decision B"), "the fresh decision");
        assert!(text.contains("new"), "the fresh event");
        assert!(!text.contains("Decision A"), "committed history stays out");
        assert!(!text.contains("`old`"), "committed history stays out");
        let _ = std::fs::remove_dir_all(&tmp);
    }
}
